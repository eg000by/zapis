-- Пакеты («N занятий одним платежом») убраны. Неоплаченные предложения не удаляем,
-- а отменяем: у части из них уже есть ссылка ЮKassa, и если по ней всё же заплатят,
-- вебхук должен найти счёт и засчитать оплату. Применять ПОСЛЕ деплоя кода без
-- пакетов: прежняя версия выставила бы предложения заново.
UPDATE "payments" SET "status" = 'canceled' WHERE "status" = 'unpaid' AND ("kind" = 'package' OR "kind" LIKE 'package:%');
